-- Loan amortization dashboard (shared, unowned rows)
create table if not exists loan_settings (
  id integer primary key check (id = 1),
  principal numeric(12,2) not null,
  tna_declared numeric(8,4) not null,
  term_months integer not null,
  start_date date not null,
  due_day integer not null default 5,
  title text not null default 'Amortizacion de vivienda'
);

create table if not exists installments (
  n integer primary key,
  due_date date not null,
  year integer not null,
  month integer not null,
  cuota numeric(12,2) not null,
  interest numeric(12,2) not null,
  amortization numeric(12,2) not null,
  opening_balance numeric(12,2) not null,
  closing_balance numeric(12,2) not null
);

create table if not exists payments (
  id serial primary key,
  installment_n integer not null references installments(n),
  paid_on date not null,
  amount_ars numeric(14,2),
  fx_rate numeric(12,4) not null,
  amount_usd numeric(12,2) not null,
  note text,
  created_at timestamptz not null default now()
);

create index if not exists payments_installment_idx on payments (installment_n);
create index if not exists payments_paid_on_idx on payments (paid_on);

create table if not exists fx_quotes (
  id serial primary key,
  captured_at timestamptz not null default now(),
  buy numeric(12,4) not null,
  sell numeric(12,4) not null,
  source text not null
);

